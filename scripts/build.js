// Bundles the pack's data files into app/base-data.js so the static site starts with data loaded.
// Usage: node scripts/build.js   (then deploy the app/ folder as-is)
const fs = require('fs');
const path = require('path');
const root = path.join(__dirname, '..');
const dir = path.join(root, 'data');
const files = fs.readdirSync(dir).filter(n => /\.(csv|txt)$/i.test(n))
  .map(n => ({ name: n, text: fs.readFileSync(path.join(dir, n), 'utf8') }));
const out = '/* generated by scripts/build.js from data/ */\nwindow.AXEOM_BASE_FILES = ' + JSON.stringify(files) + ';\n';
fs.writeFileSync(path.join(root, 'app', 'base-data.js'), out);
console.log('app/base-data.js:', files.map(f => f.name).join(', '), `(${Math.round(out.length / 1024)} KB)`);
